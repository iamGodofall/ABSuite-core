#!/usr/bin/env node
/**
 * Write docs/PERFORMANCE.md from the measured benchmark, and nothing else.
 *
 * Performance documentation is where honest projects quietly start lying: a
 * number is measured once, hand-copied into a README, and stays there through
 * two years of changes. This generates the document from
 * `bench/core-latest.json`, so the only way to change a published figure is to
 * re-run the benchmark.
 *
 *   pnpm bench:core && pnpm bench:doc
 *   node scripts/gen-performance-doc.mjs --check   # CI: doc must match the data
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sameGenerated } from './lib/generated.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataPath = join(root, 'bench/core-latest.json');
const docPath = join(root, 'docs/PERFORMANCE.md');
const readmePath = join(root, 'README.md');
const check = process.argv.includes('--check');

if (!existsSync(dataPath)) {
  console.error(`No measurement at ${dataPath}. Run: pnpm bench:core`);
  process.exit(1);
}

const report = JSON.parse(readFileSync(dataPath, 'utf8'));
if (report.schema !== 'absuite.bench.v1') {
  console.error(`Unexpected schema "${report.schema}" — refusing to publish numbers I cannot read.`);
  process.exit(1);
}

const env = report.environment;
const n = value => value.toLocaleString('en-US');

/** Plain-language labels for the front page. Operation ids stay in the doc. */
const README_LABELS = {
  'trace.record': 'Sign an execution into the chain',
  'trace.verify': 'Verify a record (Ed25519 + hash)',
  'chain.verify': 'Verify the whole chain',
  'capability.issue': 'Issue a capability token',
  'capability.validate': 'Check a capability',
  'explain.render': 'Explain a record',
};

const rows = report.measurements
  .map(
    m =>
      `| \`${m.operation}\` | ${n(m.opsPerSecond)} | ${m.latencyMs.p50} | ${m.latencyMs.p95} | ${m.latencyMs.p99} | ` +
      `${n(m.iterations)} | ${(m.successRate * 100).toFixed(2)}% |`
  )
  .join('\n');

const detail = report.measurements
  .map(m => `### \`${m.operation}\`\n\n${m.description}\n\n` +
    `- **${n(m.opsPerSecond)} operations/second** measured over ${n(m.iterations)} iterations ` +
    `(${n(m.warmupDiscarded)} warmup iterations discarded, concurrency ${m.concurrency}).\n` +
    `- Latency: min ${m.latencyMs.min} ms · p50 ${m.latencyMs.p50} ms · p95 ${m.latencyMs.p95} ms · ` +
    `p99 ${m.latencyMs.p99} ms · max ${m.latencyMs.max} ms (σ ${m.latencyMs.stddev} ms).\n` +
    `- ${m.failures === 0 ? 'Every iteration succeeded.' : `${n(m.failures)} iteration(s) failed: ${m.errorSample ?? 'no message recorded'}.`}`)
  .join('\n\n');

const doc = `# Performance

<!-- Generated by scripts/gen-performance-doc.mjs from bench/core-latest.json. Do not edit by hand. -->

Every number here was measured by \`pnpm bench:core\` against the real signing,
storage and verification paths — no stubs, no mocks, no extrapolation. Warmup
iterations are discarded and their count is stated. Throughput is iterations
divided by elapsed wall-clock time, never derived from a mean.

A performance figure is only true of the machine that produced it. This one is:

| | |
|---|---|
| CPU | ${env.cpuModel} |
| Cores | ${env.cpuCount} vCPU |
| Memory | ${env.memoryGb} GB |
| Platform | ${env.platform}/${env.arch} |
| Runtime | Node ${env.node} |
${env.commit ? `| Commit | \`${env.commit}\` |\n` : ''}| Measured | ${env.measuredAt} |

Your hardware will give different numbers. That is the point of stating ours:

\`\`\`bash
${report.reproduce}
\`\`\`

## Results

| Operation | ops/sec | p50 ms | p95 ms | p99 ms | Iterations | Success |
|---|---:|---:|---:|---:|---:|---:|
${rows}

Whole suite: ${(report.totalDurationMs / 1000).toFixed(1)}s.

## What each operation is

${detail}

## What these numbers are not

They are not a capacity plan. They measure single-process throughput on one
machine with local SQLite; a deployment behind a network, a shared database or a
slower disk will not reproduce them, and nothing here has been tuned to look
good. They are a floor to argue with, published so that anyone can re-run the
same command and disagree with the result.

There is no throughput figure anywhere else in this repository that did not come
from this file.
`;

/**
 * The README's table is generated too.
 *
 * It was hand-maintained for exactly one commit, which is one longer than the
 * rule allows: a figure a human types is a figure a human can round up. The
 * block between the markers is rewritten from the same data as the doc, and
 * --check fails if anyone edits it.
 */
const readmeTable = [
  '| Operation | ops/sec | p50 | p95 | p99 |',
  '|---|---:|---:|---:|---:|',
  ...report.measurements.map(m => {
    const label = README_LABELS[m.operation] ?? m.operation;
    return `| ${label} | ${n(Math.round(m.opsPerSecond))} | ${m.latencyMs.p50} ms | ${m.latencyMs.p95} ms | ${m.latencyMs.p99} ms |`;
  }),
].join('\n');

const START = '<!-- BENCH:START — generated by scripts/gen-performance-doc.mjs. Do not edit by hand. -->';
const END = '<!-- BENCH:END -->';

function renderReadme() {
  const current = readFileSync(readmePath, 'utf8');
  const from = current.indexOf(START);
  const to = current.indexOf(END);
  if (from === -1 || to === -1) {
    console.error(`README.md is missing the ${START} / ${END} markers.`);
    process.exit(1);
  }
  return current.slice(0, from) + `${START}\n${readmeTable}\n` + current.slice(to);
}

if (check) {
  const current = existsSync(docPath) ? readFileSync(docPath, 'utf8') : '';
  if (!sameGenerated(current, doc)) {
    console.error('docs/PERFORMANCE.md does not match bench/core-latest.json. Run: pnpm bench:doc');
    process.exit(1);
  }
  if (!sameGenerated(readFileSync(readmePath, 'utf8'), renderReadme())) {
    console.error('The performance table in README.md does not match bench/core-latest.json. Run: pnpm bench:doc');
    process.exit(1);
  }
  console.log('docs/PERFORMANCE.md and the README table match the measured data.');
} else {
  writeFileSync(docPath, doc);
  writeFileSync(readmePath, renderReadme());
  console.log(`Wrote ${docPath} and the README table from ${dataPath}`);
}
